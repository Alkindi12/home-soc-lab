#!/usr/bin/env bash
# Setup for the lab. Safe to re-run.
#   1. Creates .env with random strong passwords, or adds keys new stages need.
#   2. Renders the secret-bearing Wazuh config files from .env:
#        wazuh/config/wazuh_indexer/internal_users.yml  (bcrypt hashes)
#        wazuh/config/wazuh_dashboard/wazuh.yml         (API credentials)
#        wazuh/config/wazuh_cluster/authd.pass          (agent enrollment)
#   3. Generates the TLS certificates if they are missing.
# Everything it writes is gitignored.
set -euo pipefail

cd "$(dirname "$0")/.."

# Creates .env from .env.example, or adds keys that a later stage introduced
# to an existing .env. Existing values are never changed. Every "change-me"
# becomes a random password.
python3 - <<'PY'
import os, secrets, string

def strong(n=24):
    # Wazuh API policy: upper, lower, digit and symbol. Symbols avoid $ " \
    # so the values are safe in .env, YAML and Docker Compose interpolation.
    sym = ".*+?-_"
    pool = string.ascii_letters + string.digits + sym
    while True:
        p = "".join(secrets.choice(pool) for _ in range(n))
        if (any(c.islower() for c in p) and any(c.isupper() for c in p)
                and any(c.isdigit() for c in p) and any(c in sym for c in p)):
            return p

def key_of(line):
    line = line.strip()
    if not line or line.startswith("#") or "=" not in line:
        return None
    return line.split("=", 1)[0]

def fill(line):
    k = key_of(line)
    if k and line.rstrip().endswith("=change-me"):
        return f"{k}={strong()}\n"
    return line

example = open(".env.example").readlines()
if not os.path.exists(".env"):
    print("[setup] Creating .env with generated passwords")
    with open(".env", "w") as f:
        f.writelines(fill(l) for l in example)
else:
    have = {key_of(l) for l in open(".env")}
    missing = [l for l in example if key_of(l) and key_of(l) not in have]
    if missing:
        print("[setup] Adding new keys to .env: " + ", ".join(key_of(l) for l in missing))
        with open(".env", "a") as f:
            f.write("\n# Added by setup.sh\n")
            f.writelines(fill(l) for l in missing)
    else:
        print("[setup] .env is up to date, keeping it")
os.chmod(".env", 0o600)
PY

set -a; . ./.env; set +a

for v in WAZUH_VERSION INDEXER_USERNAME INDEXER_PASSWORD API_USERNAME API_PASSWORD DASHBOARD_USERNAME DASHBOARD_PASSWORD AGENT_ENROLLMENT_PASSWORD; do
  val="${!v:-}"
  if [ -z "$val" ] || [ "$val" = "change-me" ]; then
    echo "[setup] ERROR: $v is empty or still 'change-me' in .env" >&2
    exit 1
  fi
done

echo "[setup] Rendering internal_users.yml, wazuh.yml and authd.pass from .env"
python3 - <<'PY'
import os, bcrypt

def h(pw):
    # OpenSearch expects the $2y$ prefix; the algorithm is identical to $2b$.
    return bcrypt.hashpw(pw.encode(), bcrypt.gensalt(12)).decode().replace("$2b$", "$2y$", 1)

e = os.environ
users = f"""---
# Generated by scripts/setup.sh from .env. Do not edit or commit.
# The upstream demo users (kibanaro, logstash, readall, snapshotrestore)
# are deliberately left out: their default passwords are public.
_meta:
  type: "internalusers"
  config_version: 2

{e['INDEXER_USERNAME']}:
  hash: "{h(e['INDEXER_PASSWORD'])}"
  reserved: true
  backend_roles:
  - "admin"
  description: "Lab admin user"

{e['DASHBOARD_USERNAME']}:
  hash: "{h(e['DASHBOARD_PASSWORD'])}"
  reserved: true
  description: "Dashboard server user"
"""
path = "wazuh/config/wazuh_indexer/internal_users.yml"
with open(path, "w") as f:
    f.write(users)
os.chmod(path, 0o644)  # read by the indexer user inside the container

# The host id 1513629884013 must stay: the dashboard image's
# /wazuh_app_config.sh appends a second, unquoted hosts block (which breaks
# the YAML) unless it finds this exact id in the file.
wazuh_yml = f"""# Generated by scripts/setup.sh from .env. Do not edit or commit.
hosts:
  - 1513629884013:
      url: "https://wazuh.manager"
      port: 55000
      username: "{e['API_USERNAME']}"
      password: "{e['API_PASSWORD']}"
      run_as: true
"""
path = "wazuh/config/wazuh_dashboard/wazuh.yml"
with open(path, "w") as f:
    f.write(wazuh_yml)
os.chmod(path, 0o644)

# Agent enrollment password: copied into the manager at start, and given to
# the victims as the Docker secret "wazuh_enrollment".
path = "wazuh/config/wazuh_cluster/authd.pass"
with open(path, "w") as f:
    f.write(e["AGENT_ENROLLMENT_PASSWORD"] + "\n")
os.chmod(path, 0o600)
PY

# The generator leaves this directory root-owned (mode 500), so a normal user
# cannot look inside it: its existence is the signal that certificates exist.
# To regenerate: sudo rm -rf wazuh/config/wazuh_indexer_ssl_certs
if [ -d wazuh/config/wazuh_indexer_ssl_certs ]; then
  echo "[setup] TLS certificate directory exists, skipping generation"
else
  echo "[setup] Generating TLS certificates"
  docker compose -f wazuh/generate-indexer-certs.yml run --rm generator
fi

mkdir -p attacks/output   # attacker output (gitignored), owned by you

echo "[setup] Done. Start the stack with: docker compose up -d"
